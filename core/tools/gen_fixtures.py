"""Regenerates core/tests/fixtures.h from the photos in traces/fixtures/.

Runs MediaPipe once per photo and writes the 21 landmarks out as C struct
initialisers, so the C pose tests run against real model output rather than
hand-drawn coordinates. Run from the repo root:

    .venv/bin/python core/tools/gen_fixtures.py
"""

from pathlib import Path

import cv2
import mediapipe as mp
from mediapipe.tasks.python import BaseOptions, vision

ROOT = Path(__file__).resolve().parents[2]
PHOTOS = ["victory", "pointing_up", "thumbs_up"]
OUT = ROOT / "core" / "tests" / "fixtures.h"


def main() -> None:
    options = vision.HandLandmarkerOptions(
        base_options=BaseOptions(
            model_asset_path=str(ROOT / "app" / "models" / "hand_landmarker.task"),
            delegate=BaseOptions.Delegate.GPU,
        ),
        running_mode=vision.RunningMode.IMAGE,
        num_hands=1,
    )
    lines = [
        "/* GENERATED by core/tools/gen_fixtures.py - do not edit by hand.",
        " * Real MediaPipe landmarks from the photos in traces/fixtures/. */",
        "#ifndef FIXTURES_H",
        "#define FIXTURES_H",
        "",
        '#include "gesture.h"',
        "",
    ]
    with vision.HandLandmarker.create_from_options(options) as landmarker:
        for name in PHOTOS:
            bgr = cv2.imread(str(ROOT / "traces" / "fixtures" / f"{name}.jpg"))
            if bgr is None:
                raise SystemExit(f"missing photo: {name}.jpg")
            h, w = bgr.shape[:2]
            rgba = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGBA)
            result = landmarker.detect(mp.Image(image_format=mp.ImageFormat.SRGBA, data=rgba))
            if not result.hand_landmarks:
                raise SystemExit(f"no hand found in {name}.jpg")
            lines.append(f"/* {name}.jpg, {w}x{h} */")
            lines.append(f"#define FIXTURE_{name.upper()}_ASPECT {w / h:.6f}f")
            lines.append(f"static const gv_frame fixture_{name} = {{")
            lines.append("    .lm = {")
            for p in result.hand_landmarks[0]:
                lines.append(f"        {{ {p.x:.6f}f, {p.y:.6f}f, {p.z:.6f}f }},")
            lines.append("    },")
            lines.append("    .present = 1,")
            lines.append("    .t_sec = 0.0,")
            lines.append("};")
            lines.append("")
    lines.append("#endif /* FIXTURES_H */")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
