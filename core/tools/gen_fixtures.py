"""Regenerates core/tests/fixtures.h.

Two sources, both real model output rather than hand-drawn coordinates:
  - the photos in traces/fixtures/, run through MediaPipe here;
  - single frames lifted from traces/real_first_session.csv, the first live
    recording. The photos are posed (tight fists, fingers ramrod straight); the
    recording is what a relaxed hand in front of a webcam actually looks like,
    and it is where the first pose rule fell apart.
Run from the repo root:

    .venv/bin/python core/tools/gen_fixtures.py
"""

import sys
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "app"))

from main import detect_photo, make_landmarker  # noqa: E402

PHOTOS = ["victory", "pointing_up", "thumbs_up"]

# name -> 1-based line number in the recording. Chosen by measurement:
#   relaxed_two  index/middle up, ring/pinky loosely curled (wrist ratio 1.12 /
#                1.09: the old 1.15 threshold flickered on exactly this)
#   tight_two    the same pose with ring/pinky properly tucked
#   fist, open_palm  the two ways out of the pose
REAL_TRACE = ROOT / "traces" / "real_first_session.csv"
REAL_FRAMES = {"relaxed_two": 410, "tight_two": 162, "fist": 511, "open_palm": 254}

# Frames from the thumb probe clips (app/record_pinch_probe.sh): name -> (clip, 1-based line).
# The clips are not committed (recordings stay out of git); fixtures.h is the committed copy,
# so this section can only be regenerated on a machine that still has the clips.
#   pinch_open         the resize pose held: thumb and index out and apart, the rest curled
#   pinch_closed       the same hand fully pinched: fingertip gap 0.04 hand-lengths
#   pointing_thumb_in  index out, thumb tucked: must NOT arm a resize
PROBE_FRAMES = {
    "pinch_open": ("probe_pinch_open", 240),
    "pinch_closed": ("probe_pinch_move", 23),
    "pointing_thumb_in": ("probe_pointing", 211),
}
OUT = ROOT / "core" / "tests" / "fixtures.h"


def main() -> None:
    lines = [
        "/* GENERATED by core/tools/gen_fixtures.py - do not edit by hand.",
        " * Real MediaPipe landmarks from the photos in traces/fixtures/. */",
        "#ifndef FIXTURES_H",
        "#define FIXTURES_H",
        "",
        '#include "gesture.h"',
        "",
    ]
    with make_landmarker(image_mode=True) as landmarker:
        for name in PHOTOS:
            bgr = cv2.imread(str(ROOT / "traces" / "fixtures" / f"{name}.jpg"))
            if bgr is None:
                raise SystemExit(f"missing photo: {name}.jpg")
            h, w = bgr.shape[:2]
            hand = detect_photo(landmarker, bgr)
            if hand is None:
                raise SystemExit(f"no hand found in {name}.jpg")
            lines.append(f"/* {name}.jpg, {w}x{h} */")
            lines.append(f"#define FIXTURE_{name.upper()}_ASPECT {w / h:.6f}f")
            lines.append(f"static const gv_frame fixture_{name} = {{")
            lines.append("    .lm = {")
            for p in hand:
                lines.append(f"        {{ {p.x:.6f}f, {p.y:.6f}f, {p.z:.6f}f }},")
            lines.append("    },")
            lines.append("    .present = 1,")
            lines.append("    .t_sec = 0.0,")
            lines.append("};")
            lines.append("")
    trace_lines = REAL_TRACE.read_text().splitlines()
    aspect = float(trace_lines[0].split("=")[1])
    lines.append(f"/* frames from {REAL_TRACE.name}, a {aspect:.3f}:1 camera */")
    lines.append(f"#define FIXTURE_REAL_ASPECT {aspect:.6f}f")
    lines.append("")
    for name, line_no in REAL_FRAMES.items():
        fields = [float(v) for v in trace_lines[line_no - 1].split(",")]
        if len(fields) != 65 or fields[1] != 1.0:
            raise SystemExit(f"{REAL_TRACE.name}:{line_no} is not a hand frame")
        lines.append(f"/* {REAL_TRACE.name} line {line_no}, t = {fields[0]:.1f} s */")
        lines.append(f"static const gv_frame fixture_real_{name} = {{")
        lines.append("    .lm = {")
        for i in range(21):
            x, y, z = fields[2 + 3 * i : 5 + 3 * i]
            lines.append(f"        {{ {x:.6f}f, {y:.6f}f, {z:.6f}f }},")
        lines.append("    },")
        lines.append("    .present = 1,")
        lines.append("    .t_sec = 0.0,")
        lines.append("};")
        lines.append("")
    for name, (clip, line_no) in PROBE_FRAMES.items():
        path = ROOT / "traces" / f"{clip}.csv"
        if not path.exists():
            raise SystemExit(f"{path.name} is not here (probe clips are not committed); "
                             "keep the committed fixtures.h, or re-record with app/record_pinch_probe.sh")
        fields = [float(v) for v in path.read_text().splitlines()[line_no - 1].split(",")]
        if len(fields) != 66 or fields[1] != 1.0:
            raise SystemExit(f"{path.name}:{line_no} is not a 66-field hand frame")
        lines.append(f"/* {path.name} line {line_no}, t = {fields[0]:.1f} s */")
        lines.append(f"static const gv_frame fixture_real_{name} = {{")
        lines.append("    .lm = {")
        for i in range(21):
            x, y, z = fields[2 + 3 * i : 5 + 3 * i]
            lines.append(f"        {{ {x:.6f}f, {y:.6f}f, {z:.6f}f }},")
        lines.append("    },")
        lines.append("    .present = 1,")
        lines.append(f"    .handedness = {int(fields[65])},")
        lines.append("    .t_sec = 0.0,")
        lines.append("};")
        lines.append("")
    lines.append("#endif /* FIXTURES_H */")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
